#!/usr/bin/env python3
"""Turn the bootloader ELF into rtl/mem/boot_rom_init.vh (case items of boot_rom.v).

Every allocated section must sit inside the boot ROM (SOC_BOOT_BASE, SOC_BOOT_SIZE from
rtl/bus/soc_map.vh). Output: one line per word, "8'hNN: word = 32'hXXXXXXXX;".
Words after the image are not listed and read 0 in boot_rom.v.
Stops with an error if the image is larger than the ROM (256 words).

Usage: gen_boot_rom.py boot.elf -o rtl/mem/boot_rom_init.vh
"""
import argparse
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from elf2hex import SHF_ALLOC, SHT_NOBITS, read_elf  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP_FILE = os.path.join(ROOT, "rtl", "bus", "soc_map.vh")


def soc_define(name):
    """Value of `define SOC_<name> in soc_map.vh (Verilog number syntax)."""
    with open(MAP_FILE, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"\s*`define\s+SOC_%s\s+(\S+)" % name, line)
            if m:
                tok = m.group(1).replace("_", "")
                if "'h" in tok:
                    return int(tok.split("'h")[1], 16)
                return int(tok.split("'d")[-1])
    sys.exit("ERROR: gen_boot_rom: SOC_%s not found in %s" % (name, MAP_FILE))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("elf")
    ap.add_argument("-o", "--out", required=True)
    args = ap.parse_args()

    base = soc_define("BOOT_BASE")
    size = soc_define("BOOT_SIZE")
    image = bytearray()
    sections, symbols = read_elf(args.elf)
    for name, flags, stype, addr, sz, body in sections:
        if not (flags & SHF_ALLOC) or sz == 0:
            continue
        if stype == SHT_NOBITS or not (base <= addr and addr + sz <= base + size):
            sys.exit("ERROR: gen_boot_rom: section %s [0x%08x, +%d] is not code inside the boot ROM"
                     " [0x%08x, +%d]" % (name, addr, sz, base, size))
        off = addr - base
        if len(image) < off + sz:
            image.extend(bytearray(off + sz - len(image)))
        image[off:off + sz] = body
    image.extend(bytearray(-len(image) % 4))
    words = len(image) // 4
    if words == 0:
        sys.exit("ERROR: gen_boot_rom: %s has no code" % args.elf)
    if len(image) > size:
        sys.exit("ERROR: gen_boot_rom: image is %d words, the boot ROM holds %d"
                 % (words, size // 4))

    def sym(n):
        return symbols.get(n, 0)

    if sym("BOOT_IMEM_SIZE") != soc_define("IMEM_SIZE"):
        sys.exit("ERROR: gen_boot_rom: built for IMEM_SIZE %d, soc_map.vh has %d"
                 % (sym("BOOT_IMEM_SIZE"), soc_define("IMEM_SIZE")))

    lines = [
        "// boot_rom_init.vh - boot ROM contents, included inside the case statement of"
        " boot_rom.v.",
        "// Each line: <8-bit word index>: word = <instruction>. Unlisted words read 0 (illegal).",
        "// Generated by scripts/gen_boot_rom.py from fw/boot/boot.S (make boot-gen), do not edit.",
        "// UART bootloader, protocol in docs/boot.md.",
        "//   Size      %d of %d words (%d bytes)" % (words, size // 4, len(image)),
        "//   UART      %d baud at %d Hz, BAUDDIV %d" % (sym("BOOT_BAUD"), sym("BOOT_CLK_HZ"),
                                                       sym("BOOT_BAUDDIV")),
        "//   Timeout   %d cycles, then jump to 0x0000_0000" % sym("BOOT_TIMEOUT"),
        "//   IMEM      %d bytes" % sym("BOOT_IMEM_SIZE"),
        "//",
    ]
    for w in range(words):
        lines.append("8'h%02x: word = 32'h%08x;" % (w, struct.unpack_from("<I", image, 4 * w)[0]))
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("gen_boot_rom: %s, %d of %d words (%d bytes)" % (args.out, words, size // 4, len(image)))


if __name__ == "__main__":
    main()
